def num(x, digits=4):
    return f"{x:.{digits}f}".replace(".", ",").replace("-", "−")


SUP = str.maketrans("0123456789-", "⁰¹²³⁴⁵⁶⁷⁸⁹⁻")


def sci(x, digits=1):
    """3.9e-05 -> 3,9·10⁻⁵ (plain text for markdown tables)."""
    if x == 0:
        return "0"
    e = int(math.floor(math.log10(abs(x))))
    m = x / 10**e
    if abs(m) >= 9.95:
        m, e = m / 10, e + 1
    return f"{m:.{digits}f}".replace(".", ",").replace("-", "−") + "·10" + str(e).translate(SUP)


def cnum(re, im, digits=4):
    if abs(im) < 1e-12:
        return num(re, digits)
    sign = "+" if im >= 0 else "−"
    return f"{num(re, digits)} {sign} {num(abs(im), digits)}i"


