def quadrature_table():
    shape = 1 / CV**2
    kappa = int(np.floor(shape))
    r = shape - kappa
    theta = B1 / shape
    with np.errstate(invalid="ignore", divide="ignore"):
        roots, weights = roots_jacobi(8, -r, r - 1)
    xs, ws = (roots + 1) / 2, weights / weights.sum()
    rows = ["| $j$ | узел $x_j$ | вес $w_j$ | среднее фазы $\\theta x_j$ | интенсивность $1/(\\theta x_j)$ |", "|---|---|---|---|---|"]
    for j, (x, w) in enumerate(zip(xs, ws), 1):
        rows.append(f"| {j} | {num(x, 6)} | {num(w, 6)} | {num(theta * x, 4)} | {num(1 / (theta * x), 4)} |")
    return kappa, r, theta, "\n".join(rows)


def moments_check():
    """Relative error of the first 2J-1 moments of the 8-node law against the Gamma moments."""
    from works.negative_queues.revision_v7_20261107.positive_ph import gamma_ph
    s = gamma_ph(B1, CV, 8)
    a, T = s.alpha, s.generator
    inv = np.linalg.inv(-T)
    shape = 1 / CV**2
    theta = B1 / shape
    out = []
    power = np.eye(len(a))
    for k in range(1, 18):
        power = power @ inv
        m_ph = math.factorial(k) * a @ power @ np.ones(len(a))
        m_g = theta**k * np.prod([shape + i for i in range(k)])
        out.append((k, m_ph / m_g - 1))
    return out



